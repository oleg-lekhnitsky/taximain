import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const registry = path.join(root, 'cms/src/admin/design-tokens.json');
const output = path.join(root, 'cms/src/admin/design-tokens.css');
const tokens = JSON.parse(fs.readFileSync(registry, 'utf8'));
const seen = new Map();
for (const [name, value] of Object.entries(tokens)) {
  if (seen.has(value)) throw new Error(`Duplicate value ${value}: ${seen.get(value)}, ${name}`);
  seen.set(value, name);
}
const css = '/* Generated by npm run tokens:generate. Edit design-tokens.json. */\n:root, :host {\n' +
  Object.entries(tokens).map(([name, value]) => `  --${name}: ${value};`).join('\n') + '\n}\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== css) {
    throw new Error('Generated tokens are stale. Run npm run tokens:generate.');
  }
  console.log(`Checked ${seen.size} unique design token values.`);
} else {
  fs.writeFileSync(output, css);
  console.log(`Generated ${seen.size} design tokens.`);
}
